// ─── Create ───────────────────────────────────────────────────────────────────

/**
 * Creates a new household and makes the caller its first admin.
 * The invite_code is generated automatically by the DB trigger.
 */
export async function createHousehold(formData: FormData) {
  const supabase = await createClient()

  const {
    data: { user },
  } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated.' }

  const name = (formData.get('name') as string).trim()
  if (!name || name.length < 2) return { error: 'Household name must be at least 2 characters.' }
  if (name.length > 80)         return { error: 'Household name must be 80 characters or fewer.' }

  // Create the household (invite_code auto-generated by trigger)
  const { data: household, error: hErr } = await supabase
    .from('households')
    .insert({ name, created_by: user.id })
    .select('id, name, invite_code')
    .single()

  if (hErr || !household) return { error: hErr?.message ?? 'Could not create household.' }

  // Add current user as admin
  const { error: mErr } = await supabase
    .from('household_members')
    .insert({ user_id: user.id, household_id: household.id, role: 'admin' })

  if (mErr) {
    // Roll back the orphaned household
    await supabase.from('households').delete().eq('id', household.id)
    return { error: mErr.message }
  }

  revalidatePath('/', 'layout')
  return { success: true, household }
}

// ─── Join ─────────────────────────────────────────────────────────────────────

/**
 * Looks up a household by invite code and adds the caller as a member.
 * Normalises the code to uppercase so casing doesn't matter.
 */
export async function joinHousehold(formData: FormData) {
  const supabase = await createClient()

  const {
    data: { user },
  } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated.' }

  const rawCode = (formData.get('code') as string ?? '').trim().toUpperCase()
  if (rawCode.length !== 6) return { error: 'Invite codes are exactly 6 characters.' }

  // Find the household
  const { data: household, error: hErr } = await supabase
    .from('households')
    .select('id, name')
    .eq('invite_code', rawCode)
    .maybeSingle()

  if (hErr || !household) {
    return { error: 'No household found with that code. Double-check and try again.' }
  }

  // Join as member
  const { error: mErr } = await supabase
    .from('household_members')
    .insert({ user_id: user.id, household_id: household.id, role: 'member' })

  if (mErr) return { error: mErr.message }

  revalidatePath('/', 'layout')
  return { success: true, household }
}

// ─── Rename ───────────────────────────────────────────────────────────────────

