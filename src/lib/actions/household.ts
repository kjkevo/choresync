// ─── Kids mode ────────────────────────────────────────────────────────────────

export async function setMemberKidsMode(memberId: string, householdId: string, enable: boolean) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated.' }

  const { data: isAdmin } = await supabase.rpc('is_household_admin', { p_household_id: householdId })
  if (!isAdmin) return { error: 'Only admins can change roles.' }

  const { data: target } = await supabase
    .from('household_members')
    .select('user_id, role')
    .eq('id', memberId)
    .eq('household_id', householdId)
    .maybeSingle()

  if (!target) return { error: 'Member not found.' }
  if (target.user_id === user.id) return { error: 'You cannot put yourself in kids mode.' }
  if (target.role === 'admin') return { error: 'Demote this admin to member first.' }

  const { error } = await supabase
    .from('household_members')
    .update({ role: enable ? 'kids' : 'member' })
    .eq('id', memberId)

  if (error) return { error: error.message }
  revalidatePath('/household')
  return { success: true }
}

// ─── Join via shareable link ──────────────────────────────────────────────────

export async function joinViaLink(code: string, displayName: string) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return { error: 'Please sign in first to join a household.' }

  const upperCode = code.trim().toUpperCase()

  const { data: household } = await supabase
    .from('households')
    .select('id, name')
    .eq('invite_code', upperCode)
    .maybeSingle()

  if (!household) return { error: 'Invalid or expired invite link.' }

  const { data: alreadyIn } = await supabase
    .from('household_members')
    .select('id')
    .eq('user_id', user.id)
    .eq('household_id', household.id)
    .maybeSingle()

  if (alreadyIn) return { error: 'You are already a member of this household.' }

  if (displayName.trim()) {
    await supabase.from('users').update({ full_name: displayName.trim() }).eq('id', user.id)
  }

  const { error: joinErr } = await supabase
    .from('household_members')
    .insert({ user_id: user.id, household_id: household.id, role: 'member' })

  if (joinErr) return { error: joinErr.message }

  revalidatePath('/', 'layout')
  return { success: true, householdName: household.name }
}
