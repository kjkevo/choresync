// ─── Member role ──────────────────────────────────────────────────────────────

/**
 * Admin-only: promote a member to admin or demote an admin to member.
 * Guards against demoting the last admin.
 */
export async function updateMemberRole(
  memberId:    string,
  householdId: string,
  newRole:     'admin' | 'member'
) {
  const supabase = await createClient()

  const { data: isAdmin } = await supabase.rpc('is_household_admin', {
    p_household_id: householdId,
  })
  if (!isAdmin) return { error: 'Only admins can change member roles.' }

  if (newRole === 'member') {
    // Ensure at least one admin will remain
    const { count } = await supabase
      .from('household_members')
      .select('*', { count: 'exact', head: true })
      .eq('household_id', householdId)
      .eq('role', 'admin')

    if ((count ?? 0) <= 1) {
      return { error: 'Cannot demote the last admin. Promote another member first.' }
    }
  }

  const { error } = await supabase
    .from('household_members')
    .update({ role: newRole })
    .eq('id', memberId)

  if (error) return { error: error.message }

  revalidatePath('/household')
  return { success: true }
}

// ─── Remove member ────────────────────────────────────────────────────────────

/**
 * Admin-only: remove any other member from the household.
 * An admin cannot remove themselves via this action — use leaveHousehold instead.
 */
export async function removeMember(memberId: string, householdId: string) {
  const supabase = await createClient()

  const {
    data: { user },
  } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated.' }

  const { data: isAdmin } = await supabase.rpc('is_household_admin', {
    p_household_id: householdId,
  })
  if (!isAdmin) return { error: 'Only admins can remove members.' }

  // Fetch the target membership
  const { data: target } = await supabase
    .from('household_members')
    .select('user_id, role')
    .eq('id', memberId)
    .eq('household_id', householdId)
    .maybeSingle()

  if (!target) return { error: 'Member not found in this household.' }
  if (target.user_id === user.id) return { error: 'Use "Leave Household" to remove yourself.' }

  if (target.role === 'admin') {
    const { count } = await supabase
      .from('household_members')
      .select('*', { count: 'exact', head: true })
      .eq('household_id', householdId)
      .eq('role', 'admin')

    if ((count ?? 0) <= 1) {
      return { error: 'Cannot remove the last admin. Promote another member first.' }
    }
  }

  const { error } = await supabase
    .from('household_members')
    .delete()
    .eq('id', memberId)

  if (error) return { error: error.message }

  revalidatePath('/household')
  return { success: true }
}

// ─── Leave ────────────────────────────────────────────────────────────────────

/**
 * Lets the current user exit a household.
 * If they are the last admin and other members exist, they must promote
 * someone before leaving.
 */
export async function leaveHousehold(householdId: string) {
  const supabase = await createClient()

  const {
    data: { user },
  } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated.' }

  // Fetch caller's membership
  const { data: membership } = await supabase
    .from('household_members')
    .select('id, role')
    .eq('user_id', user.id)
    .eq('household_id', householdId)
    .maybeSingle()

  if (!membership) return { error: 'You are not a member of this household.' }

  if (membership.role === 'admin') {
    const { count: adminCount } = await supabase
      .from('household_members')
      .select('*', { count: 'exact', head: true })
      .eq('household_id', householdId)
      .eq('role', 'admin')

    const { count: totalCount } = await supabase
      .from('household_members')
      .select('*', { count: 'exact', head: true })
      .eq('household_id', householdId)

    const isLastAdmin = (adminCount ?? 0) <= 1
    const hasOthers   = (totalCount ?? 0) > 1

    if (isLastAdmin && hasOthers) {
      return {
        error:
          'You are the only admin. Promote another member to admin before leaving.',
      }
    }
  }

  const { error } = await supabase
    .from('household_members')
    .delete()
    .eq('id', membership.id)

  if (error) return { error: error.message }

  revalidatePath('/', 'layout')
  redirect('/onboarding')
}

